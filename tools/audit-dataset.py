#!/usr/bin/env python3
"""
audit-dataset.py — quality dashboard for js/pln-java-grid-data.js.

Reads the generated JS data file, runs structural + semantic checks, prints a
report and (with --strict) exits 1 on critical findings so the audit can gate
CI / pre-commit.

Checks:
  1. Orphan nodes — stations with zero edges after inference (HIGH).
  2. Geographic outliers — lat/lng outside Java + Bali bbox (CRITICAL).
  3. Cross-tier impossible — 20 kV node directly connected to 500 kV station
     without a 150 kV step in between (HIGH; warns, since some real
     IBT-bypass distribution lines do exist).
  4. Confidence distribution — flag if >50% of any voltage tier is 'low'.
  5. Bali isolation — at least 1 edge must connect Bali to Java.
  6. Province coverage — all 5 provinces (jakarta-banten/jabar/jateng/jatim/bali)
     must have ≥10 nodes each.
  7. Duplicate IDs — `id` field must be globally unique.
  8. Missing required fields — every node must have id/name/lat/lng/voltage/prov.

Usage:
    python3 tools/audit-dataset.py [--strict] [--json]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

ROOT = Path(__file__).resolve().parent.parent
DATA_FILE = ROOT / "js" / "pln-java-grid-data.js"

JAVA_BALI_BBOX = (-9.0, 105.0, -5.0, 116.0)  # (lat_min, lng_min, lat_max, lng_max)
PROVINCES = ("jakarta-banten", "jabar", "jateng", "jatim", "bali")
REQUIRED_NODE_FIELDS = ("id", "name", "lat", "lng", "voltage", "prov")


# --------------------------------------------------------------------------
# Lightweight JS-data parser (extracts the nodes[] and edges[] arrays only)
# --------------------------------------------------------------------------

def parse_data_file(text: str) -> Dict[str, List[Dict[str, Any]]]:
    """Convert the JS object literal to Python dicts via regex + ast.literal_eval.

    The data file is generated by tools/build-osm-dataset.py with a stable
    shape (single-quoted strings, no functions, no comments inside objects).
    We rewrite single quotes to double quotes and use json.loads — fast and
    robust for this controlled input.
    """
    nodes_match = re.search(r"nodes:\s*\[(.*?)\n\s*\],", text, re.DOTALL)
    edges_match = re.search(r"edges:\s*\[(.*?)\n\s*\],", text, re.DOTALL)
    if not nodes_match or not edges_match:
        raise SystemExit("audit: cannot find nodes[] or edges[] in data file")

    nodes = _parse_array(nodes_match.group(1))
    edges = _parse_array(edges_match.group(1))
    return {"nodes": nodes, "edges": edges}


def _parse_array(body: str) -> List[Dict[str, Any]]:
    """Parse a list of JS object literals into Python dicts."""
    out: List[Dict[str, Any]] = []
    # Each top-level object is `{ ... },` on its own line
    for line in body.splitlines():
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        if line.endswith(","):
            line = line[:-1]
        if not (line.startswith("{") and line.endswith("}")):
            continue
        out.append(_js_obj_to_dict(line))
    return out


def _js_obj_to_dict(s: str) -> Dict[str, Any]:
    """Convert a single JS object literal to a Python dict.

    Handles: bare keys, single-quoted strings, numbers, booleans, null,
    list literals, nested objects (1 level — sufficient for our schema).
    """
    json_text = _js_to_json(s)
    return json.loads(json_text)


def _js_to_json(s: str) -> str:
    """Rewrite a JS object literal into JSON. Quotes bare keys, swaps quotes."""
    # Quote bare keys: { foo: ... } -> { "foo": ... }
    # Match keys after { or , — followed by colon
    s = re.sub(r"([{,]\s*)([a-zA-Z_][\w]*)\s*:", r'\1"\2":', s)
    # Convert single-quoted strings to double-quoted, preserving escapes
    s = _swap_quotes(s)
    return s


def _swap_quotes(s: str) -> str:
    """Convert 'foo' style strings to "foo" style for JSON parsing."""
    out = []
    i = 0
    while i < len(s):
        c = s[i]
        if c == "'":
            # Read single-quoted string body, escape inner double-quotes
            buf = ['"']
            i += 1
            while i < len(s) and s[i] != "'":
                if s[i] == "\\" and i + 1 < len(s):
                    nxt = s[i + 1]
                    if nxt == "'":
                        buf.append("'")
                        i += 2
                        continue
                    buf.append(s[i:i + 2])
                    i += 2
                    continue
                if s[i] == '"':
                    buf.append('\\"')
                else:
                    buf.append(s[i])
                i += 1
            buf.append('"')
            out.append("".join(buf))
            i += 1  # skip closing single quote
        elif c == '"':
            # Pass through double-quoted strings unchanged
            j = i + 1
            while j < len(s) and s[j] != '"':
                if s[j] == "\\":
                    j += 2
                else:
                    j += 1
            out.append(s[i:j + 1])
            i = j + 1
        else:
            out.append(c)
            i += 1
    return "".join(out)


# --------------------------------------------------------------------------
# Audit checks
# --------------------------------------------------------------------------

def check_required_fields(nodes: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    out = []
    for n in nodes:
        missing = [f for f in REQUIRED_NODE_FIELDS if f not in n or n[f] is None]
        if missing:
            out.append({"severity": "CRITICAL", "id": n.get("id", "?"),
                        "issue": "missing-fields", "missing": missing})
    return out


def check_duplicate_ids(nodes: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    seen: Dict[str, int] = {}
    out = []
    for n in nodes:
        nid = n.get("id")
        if nid is None:
            continue
        seen[nid] = seen.get(nid, 0) + 1
    for nid, count in seen.items():
        if count > 1:
            out.append({"severity": "CRITICAL", "id": nid,
                        "issue": "duplicate-id", "count": count})
    return out


def check_geographic_outliers(nodes: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    out = []
    lat_min, lng_min, lat_max, lng_max = JAVA_BALI_BBOX
    for n in nodes:
        lat = n.get("lat")
        lng = n.get("lng")
        if lat is None or lng is None:
            continue
        if not (lat_min <= lat <= lat_max and lng_min <= lng <= lng_max):
            out.append({"severity": "CRITICAL", "id": n.get("id", "?"),
                        "issue": "outside-bbox", "lat": lat, "lng": lng,
                        "name": n.get("name", "")})
    return out


def check_orphan_stations(nodes: List[Dict[str, Any]],
                           edges: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Flag orphan TRANSMISSION-tier stations (≥70 kV). 20 kV distribution
    stations are expected to be unconnected in our model — we don't crawl
    the full feeder graph."""
    connected = set()
    for e in edges:
        connected.add(e.get("from"))
        connected.add(e.get("to"))
    out = []
    for n in nodes:
        if n.get("kind") != "station":
            continue
        v = n.get("voltage")
        if v is None or v < 70:
            continue   # 20 kV distribution orphans are expected, not flagged
        if n.get("id") in connected:
            continue
        out.append({"severity": "HIGH", "id": n.get("id", "?"),
                    "issue": "orphan-station", "name": n.get("name", ""),
                    "voltage": v, "prov": n.get("prov")})
    return out


def check_confidence_distribution(nodes: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Per voltage tier: flag if >50% of nodes are confidence='low'."""
    by_v: Dict[Any, Dict[str, int]] = {}
    for n in nodes:
        v = n.get("voltage")
        c = n.get("confidence", "unknown")
        by_v.setdefault(v, {"high": 0, "medium": 0, "low": 0, "unknown": 0})
        by_v[v][c if c in ("high", "medium", "low") else "unknown"] += 1
    out = []
    for v, counts in by_v.items():
        total = sum(counts.values())
        if total == 0:
            continue
        low_pct = counts["low"] / total * 100
        if low_pct > 50:
            out.append({"severity": "HIGH", "issue": "confidence-low-skew",
                        "voltage": v, "low_pct": round(low_pct, 1),
                        "total": total})
    return out


def check_province_coverage(nodes: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    by_p: Dict[str, int] = {p: 0 for p in PROVINCES}
    for n in nodes:
        p = n.get("prov")
        if p in by_p:
            by_p[p] += 1
    out = []
    for p, count in by_p.items():
        if count < 10:
            out.append({"severity": "HIGH", "issue": "province-sparse",
                        "prov": p, "node_count": count})
    return out


def check_bali_isolation(nodes: List[Dict[str, Any]],
                         edges: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    bali_ids = {n["id"] for n in nodes if n.get("prov") == "bali" and "id" in n}
    if not bali_ids:
        return [{"severity": "CRITICAL", "issue": "bali-no-nodes"}]
    crossings = 0
    for e in edges:
        a, b = e.get("from"), e.get("to")
        if (a in bali_ids) != (b in bali_ids):
            crossings += 1
    if crossings == 0:
        return [{"severity": "CRITICAL", "issue": "bali-island-isolated",
                 "node_count": len(bali_ids)}]
    return []


def check_cross_tier_jumps(nodes: List[Dict[str, Any]],
                            edges: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Flag 500↔20 or 275↔20 direct edges (skip plant evac which is tagged)."""
    by_id: Dict[str, Dict[str, Any]] = {n["id"]: n for n in nodes if "id" in n}
    out = []
    for e in edges:
        if e.get("source") == "inferred-evacuation":
            continue
        a, b = by_id.get(e.get("from")), by_id.get(e.get("to"))
        if not a or not b:
            continue
        va = a.get("voltage")
        vb = b.get("voltage")
        if {va, vb} & {500, 275} and {va, vb} & {20}:
            out.append({"severity": "HIGH", "issue": "cross-tier-jump",
                        "from": e.get("from"), "to": e.get("to"),
                        "from_v": va, "to_v": vb})
    return out


# --------------------------------------------------------------------------
# Reporting
# --------------------------------------------------------------------------

CHECKS = [
    ("required_fields", check_required_fields, ("nodes",)),
    ("duplicate_ids", check_duplicate_ids, ("nodes",)),
    ("geographic_outliers", check_geographic_outliers, ("nodes",)),
    ("orphan_stations", check_orphan_stations, ("nodes", "edges")),
    ("confidence_distribution", check_confidence_distribution, ("nodes",)),
    ("province_coverage", check_province_coverage, ("nodes",)),
    ("bali_isolation", check_bali_isolation, ("nodes", "edges")),
    ("cross_tier_jumps", check_cross_tier_jumps, ("nodes", "edges")),
]


def run_audit(data: Dict[str, List[Dict[str, Any]]]) -> Dict[str, List[Dict[str, Any]]]:
    findings: Dict[str, List[Dict[str, Any]]] = {}
    for name, fn, args in CHECKS:
        kwargs = {k: data[k] for k in args}
        # Call positionally
        if args == ("nodes",):
            findings[name] = fn(data["nodes"])
        else:
            findings[name] = fn(data["nodes"], data["edges"])
    return findings


def format_human(findings: Dict[str, List[Dict[str, Any]]],
                 nodes: List[Dict[str, Any]],
                 edges: List[Dict[str, Any]]) -> str:
    lines = []
    lines.append("=" * 72)
    lines.append("PLN Java-Bali grid dataset audit")
    lines.append("=" * 72)
    lines.append(f"  Nodes: {len(nodes)}  ({sum(1 for n in nodes if n.get('kind')=='station')} stations + "
                 f"{sum(1 for n in nodes if n.get('kind')=='plant')} plants)")
    lines.append(f"  Edges: {len(edges)}")
    lines.append("")

    total_critical = 0
    total_high = 0
    for check_name, results in findings.items():
        if not results:
            lines.append(f"  [PASS] {check_name}")
            continue
        crit = sum(1 for r in results if r.get("severity") == "CRITICAL")
        high = sum(1 for r in results if r.get("severity") == "HIGH")
        total_critical += crit
        total_high += high
        flag = "CRIT" if crit else ("HIGH" if high else "WARN")
        lines.append(f"  [{flag}] {check_name}: {len(results)} finding(s)")
        for r in results[:5]:
            lines.append(f"         - {r}")
        if len(results) > 5:
            lines.append(f"         ... +{len(results)-5} more")

    lines.append("")
    lines.append(f"Summary: {total_critical} CRITICAL, {total_high} HIGH")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--strict", action="store_true",
                        help="exit 1 if any CRITICAL findings")
    parser.add_argument("--json", action="store_true",
                        help="emit findings as JSON instead of human report")
    args = parser.parse_args()

    if not DATA_FILE.exists():
        print(f"audit: data file not found: {DATA_FILE}", file=sys.stderr)
        return 2

    text = DATA_FILE.read_text()
    data = parse_data_file(text)
    findings = run_audit(data)

    if args.json:
        print(json.dumps({"summary": {"nodes": len(data["nodes"]),
                                       "edges": len(data["edges"])},
                          "findings": findings}, indent=2))
    else:
        print(format_human(findings, data["nodes"], data["edges"]))

    if args.strict:
        critical = sum(1 for results in findings.values()
                       for r in results if r.get("severity") == "CRITICAL")
        if critical:
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
