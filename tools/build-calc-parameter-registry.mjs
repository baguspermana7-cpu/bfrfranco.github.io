#!/usr/bin/env node
/**
 * build-calc-parameter-registry.mjs — PRD-P10 stage 1: the calculator parameter registry.
 *
 * Reads data/calc-parameters.curated.json (labels, formulas, inputs, sources: written by hand) and renders each
 * calculator page at its defaults in headless Chrome. For every record it:
 *   - finds the ONE element carrying data-basis-param="<id>" (zero or two is an error);
 *   - reads its text (`display`) and parses the number (`value`, K/M/B suffixes, sign, %);
 *   - moves each declared input on its own (a number by +10 %, a list or radio group to the next option, as the
 *     sensitivity panel does) and re-reads the cell: the inputs that change it are `dependsOnInputs`, measured,
 *     never declared. A Pro-only input inside .locked is not moved.
 * Writes data/calc-parameters.json and its window twin js/calc-parameters.js (RZ_CALC_PARAMETERS).
 *
 *   node tools/build-calc-parameter-registry.mjs           write both files
 *   node tools/build-calc-parameter-registry.mjs --check   exit 1 when a fresh build differs from the files
 */
import { createServer } from 'node:http';
import { readFile, writeFile } from 'node:fs/promises';
import { readFileSync } from 'node:fs';
import { join, extname, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import puppeteer from 'puppeteer';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CURATED = join(ROOT, 'data/calc-parameters.curated.json');
const OUT_JSON = join(ROOT, 'data/calc-parameters.json');
const OUT_JS = join(ROOT, 'js/calc-parameters.js');
const SETTLE_MS = 700;

export function engineDataVersion() {
  const win = { console };
  win.window = win;
  win.localStorage = { getItem() { return null; }, setItem() {}, removeItem() {} };
  win.CustomEvent = function () {}; win.dispatchEvent = function () { return true; };
  win.addEventListener = function () {}; win.removeEventListener = function () {};
  vm.runInContext(readFileSync(join(ROOT, 'rz-engine.js'), 'utf8'), vm.createContext(win));
  return String(win.RZEngine.data.version);
}

export function twin(json) {
  return '/* GENERATED by tools/build-calc-parameter-registry.mjs from data/calc-parameters.curated.json and the rendered\n'
    + ' * calculator pages - do not edit. PRD-P10. Read by js/rz-basis-drawer.js (data-rz-registry="RZ_CALC_PARAMETERS"). */\n'
    + 'window.RZ_CALC_PARAMETERS = ' + json + ';\n';
}

const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.mjs': 'text/javascript', '.css': 'text/css', '.json': 'application/json',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.webp': 'image/webp', '.woff2': 'font/woff2' };
export async function serve() {
  const server = createServer(async (req, res) => {
    try {
      const path = decodeURIComponent(new URL(req.url, 'http://x').pathname);
      const file = join(ROOT, path === '/' ? 'index.html' : path);
      if (!file.startsWith(ROOT)) { res.writeHead(403).end(); return; }
      const body = await readFile(file);   /* read first: a missing file must 404, not throw after a 200 head */
      res.writeHead(200, { 'content-type': MIME[extname(file)] || 'application/octet-stream' }).end(body);
    } catch { res.writeHead(404).end(); }
  });
  await new Promise((ok) => server.listen(0, '127.0.0.1', ok));
  return { server, base: `http://127.0.0.1:${server.address().port}/` };
}

export async function openPage(browser, base, page) {
  const tab = await browser.newPage();
  await tab.setViewport({ width: 1366, height: 900 });
  await tab.setRequestInterception(true);
  tab.on('request', (r) => (r.url().startsWith(base) ? r.continue() : r.abort()));
  await tab.evaluateOnNewDocument(() => { try { localStorage.clear(); sessionStorage.clear(); } catch (e) { /* no storage */ } });
  await tab.goto(base + page, { waitUntil: 'load', timeout: 60000 });
  await new Promise((ok) => setTimeout(ok, 1500));
  return tab;
}

/* In-page: read every hook, then move each declared input and re-read. */
function measureInPage(records, settleMs) {
  function num(text) {
    if (text == null) return NaN;
    var s = String(text).replace(/,/g, '').replace(/−/g, '-');
    var m = s.match(/\d+(?:\.\d+)?/);
    if (!m) return NaN;
    var v = parseFloat(m[0]);
    if (/[-(]\s*[^\d\s]{0,3}\s*$/.test(s.slice(0, m.index))) v = -v;
    /* a K/M/B multiplier, not the first letter of a unit ("1,464 kW" is 1464, "$6K/kW" is 6000) */
    var sm = s.slice(m.index + m[0].length).trim().match(/^([KkMB])(?![A-Za-z])/);
    if (sm) v *= sm[1] === 'M' ? 1e6 : sm[1] === 'B' ? 1e9 : 1e3;
    /* ">20" (payback not reached within the horizon) is a bound, not the number 20 */
    if (/^[<>]/.test(s.trim())) return NaN;
    return v;
  }
  function text(id) {
    /* a hook parked while the page gates the value (rz-calc-basis.js) still counts: the value is in the DOM */
    var els = document.querySelectorAll('[data-basis-param="' + id + '"],[data-rz-basis-gated="' + id + '"]');
    return { n: els.length, t: els.length === 1 ? els[0].textContent.replace(/\s+/g, ' ').trim() : null };
  }
  function fire(el) { ['input', 'change'].forEach(function (t) { el.dispatchEvent(new Event(t, { bubbles: true })); }); }
  function wait(ms) { return new Promise(function (ok) { setTimeout(ok, ms); }); }
  /* Each input is probed several ways so a cell rounded for display cannot hide a dependency (LTC FYI, v3.54.0:
   * "Region" moved calc.capex.total but not "$11K/kW"): a number goes to x0.5, x1.1 and x2 of its default (inside
   * min/max, on the range step); a list or radio group goes to up to 6 other options spread across it. */
  function numVariants(el, b) {
    var lo = el.min !== '' ? parseFloat(el.min) : -Infinity, hi = el.max !== '' ? parseFloat(el.max) : Infinity;
    var raw = b === 0 ? [isFinite(hi) ? hi * 0.1 : 1, isFinite(hi) ? hi * 0.5 : 10] : [b * 1.1, b * 0.5, b * 2, b * 0.9];
    var st = el.type === 'range' && el.step && parseFloat(el.step) > 0 ? parseFloat(el.step) : 0, o = isFinite(lo) ? lo : 0;
    var out = [];
    raw.forEach(function (v) {
      v = Math.min(hi, Math.max(lo, v));
      if (st) v = o + Math.round((v - o) / st) * st;
      v = parseFloat(v.toFixed(6));
      if (v !== b && out.indexOf(v) < 0) out.push(v);
    });
    if (!out.length && st) out.push(parseFloat((b + st * (b + st > hi ? -1 : 1)).toFixed(6)));
    return out;
  }
  function spread(n, from) {
    var all = [];
    for (var i = 0; i < n; i++) if (i !== from) all.push(i);
    if (all.length <= 6) return all;
    var pick = [];
    for (var k = 0; k < 6; k++) pick.push(all[Math.round(k * (all.length - 1) / 5)]);
    return pick.filter(function (v, i, a) { return a.indexOf(v) === i; });
  }
  function probes(spec) {
    if (spec.name) {
      var rs = [].slice.call(document.querySelectorAll('input[name="' + spec.name + '"]'));
      var i = rs.findIndex(function (r) { return r.checked; });
      if (rs.length < 2 || i < 0 || rs[i].closest('.locked')) return null;
      var from = rs[i];
      return spread(rs.length, i).map(function (j) {
        return { apply: function () { rs[j].checked = true; fire(rs[j]); }, undo: function () { from.checked = true; fire(from); } };
      });
    }
    var el = document.getElementById(spec.id);
    if (!el || el.closest('.locked') || el.disabled) return null;
    var old = el.value;
    var undo = function () { el.value = old; fire(el); };
    if (el.tagName === 'SELECT') {
      var opts = [].slice.call(el.options).filter(function (o) { return !o.disabled; });
      var j0 = opts.map(function (o) { return o.value; }).indexOf(old);
      if (opts.length < 2 || j0 < 0) return null;
      return spread(opts.length, j0).map(function (j) { return { apply: function () { el.value = opts[j].value; fire(el); }, undo: undo }; });
    }
    var b = parseFloat(old);
    if (!isFinite(b)) return null;
    var vs = numVariants(el, b);
    if (!vs.length) return null;
    return vs.map(function (v) { return { apply: function () { el.value = String(v); fire(el); }, undo: undo }; });
  }
  /* A record whose engineFn names a result path ("RZEngine.models.capex.detailed → costs.ups") is also read raw: the
   * engine function is wrapped so its last return is kept, and the path is compared exactly, not as rounded text. */
  var rawLast = {};
  function rawSpec(r) {
    var m = /^(RZEngine(?:\.[A-Za-z_$][\w$]*)+)\s*→\s*([\w.]+)$/.exec(r.engineFn || '');
    return m ? { fn: m[1], path: m[2] } : null;
  }
  function wrap(fnPath) {
    if (rawLast.hasOwnProperty(fnPath)) return;
    var parts = fnPath.split('.'), host = window;
    for (var i = 0; i < parts.length - 1; i++) { host = host && host[parts[i]]; }
    var name = parts[parts.length - 1];
    if (!host || typeof host[name] !== 'function') return;
    var orig = host[name];
    rawLast[fnPath] = undefined;
    try { host[name] = function () { var v = orig.apply(this, arguments); rawLast[fnPath] = v; return v; }; } catch (e) { delete rawLast[fnPath]; }
  }
  function raw(r) {
    var sp = rawSpec(r);
    if (!sp || !rawLast.hasOwnProperty(sp.fn) || rawLast[sp.fn] == null) return undefined;
    var v = rawLast[sp.fn];
    sp.path.split('.').forEach(function (k) { v = v == null ? v : v[k]; });
    return typeof v === 'number' ? v : undefined;
  }
  return (async function () {
    records.forEach(function (r) { var sp = rawSpec(r); if (sp) wrap(sp.fn); });
    var first = records[0] && records[0].inputs[0];
    var kick = first && probes(first);   /* one recalculation so every wrapped engine has a last return */
    if (kick && kick.length) { kick[0].apply(); await wait(settleMs); kick[0].undo(); await wait(settleMs); }
    var out = {};
    records.forEach(function (r) {
      var t = text(r.id);
      var v0 = num(t.t), r0 = raw(r);
      /* the raw path counts only when it IS the shown number (within display rounding): "$11K/kW" reads the
       * engine total but shows total / kW, so its raw total is not its value */
      if (r0 !== undefined && !(isFinite(v0) && Math.abs(r0 - v0) <= 0.05 * Math.max(Math.abs(r0), 1e-9))) r0 = undefined;
      out[r.id] = { count: t.n, display: t.t, value: v0, raw: r0, moved: [], movedRawOnly: [], unmovable: [] };
    });
    var inputs = {};
    records.forEach(function (r) { r.inputs.forEach(function (s) { inputs[s.id || 'name:' + s.name] = s; }); });
    var keys = Object.keys(inputs);
    function uses(r, key) { return r.inputs.some(function (s) { return (s.id || 'name:' + s.name) === key; }); }
    for (var k = 0; k < keys.length; k++) {
      var ps = probes(inputs[keys[k]]);
      if (!ps) { records.forEach(function (r) { if (uses(r, keys[k])) out[r.id].unmovable.push(inputs[keys[k]].label); }); continue; }
      var shown = {}, rawMoved = {};
      for (var q = 0; q < ps.length; q++) {
        ps[q].apply();
        await wait(settleMs);
        records.forEach(function (r) {
          if (!uses(r, keys[k])) return;
          if (text(r.id).t !== out[r.id].display) shown[r.id] = true;
          var rv = raw(r);
          if (out[r.id].raw !== undefined && rv !== undefined && rv !== out[r.id].raw) rawMoved[r.id] = true;
        });
        ps[q].undo();
        await wait(settleMs);
      }
      records.forEach(function (r) {
        if (!uses(r, keys[k])) return;
        if (shown[r.id] || rawMoved[r.id]) out[r.id].moved.push(inputs[keys[k]].label);
        if (rawMoved[r.id] && !shown[r.id]) out[r.id].movedRawOnly.push(inputs[keys[k]].label);
      });
    }
    return out;
  })();
}

export async function build() {
  const cur = JSON.parse(await readFile(CURATED, 'utf8'));
  const reg = JSON.parse(await readFile(join(ROOT, 'data/calculators.json'), 'utf8'));
  const pageOf = Object.fromEntries(reg.calculators.map((c) => [c.calc, c.page]));
  const errors = [];
  const byCalc = {};
  for (const r of cur.records) (byCalc[r.calc] = byCalc[r.calc] || []).push(r);
  const { server, base } = await serve();
  const browser = await puppeteer.launch({ headless: true, args: ['--no-sandbox', '--disable-setuid-sandbox'] });
  const params = [];
  try {
    for (const calc of Object.keys(byCalc)) {
      const page = pageOf[calc];
      if (!page) { errors.push(calc + ': not in data/calculators.json'); continue; }
      const tab = await openPage(browser, base, page);
      const m = await tab.evaluate(measureInPage, byCalc[calc], SETTLE_MS);
      await tab.close();
      for (const r of byCalc[calc]) {
        const got = m[r.id];
        if (got.count !== 1) errors.push(r.id + ': ' + got.count + ' elements carry this hook on ' + page + ' at defaults (need exactly 1)');
        else if (!isFinite(got.value) && !/^[<>]/.test(got.display)) errors.push(r.id + ': "' + got.display + '" is not a number');
        params.push({ ...r, page, kind: 'derived', scope: page, display: got.display, value: isFinite(got.value) ? got.value : null,
          dependsOnInputs: got.moved, notMovable: got.unmovable, consumers: [{ page }], tests: ['tools/test-calc-parameter-registry.mjs'] });
      }
    }
  } finally {
    await browser.close();
    server.close();
  }
  const doc = { version: 1, generatedBy: 'tools/build-calc-parameter-registry.mjs', engineDataVersion: engineDataVersion(),
    scope: 'PRD-P10 stage 1: headline results of capex, opex, tco, roi, carbon, pue at page defaults', parameters: params };
  return { doc, json: JSON.stringify(doc, null, 1), errors };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { json, errors } = await build();
  if (errors.length) { console.log('ERRORS:\n  ' + errors.join('\n  ')); process.exit(1); }
  if (process.argv.includes('--check')) {
    const a = await readFile(OUT_JSON, 'utf8').catch(() => ''), b = await readFile(OUT_JS, 'utf8').catch(() => '');
    if (a !== json + '\n' || b !== twin(json)) { console.log('data/calc-parameters.json or js/calc-parameters.js is STALE - run node tools/build-calc-parameter-registry.mjs'); process.exit(1); }
    console.log('calc parameter registry fresh (' + JSON.parse(json).parameters.length + ' records)');
  } else {
    await writeFile(OUT_JSON, json + '\n');
    await writeFile(OUT_JS, twin(json));
    console.log('wrote data/calc-parameters.json + js/calc-parameters.js (' + JSON.parse(json).parameters.length + ' records)');
  }
}
