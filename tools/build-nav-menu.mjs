#!/usr/bin/env node
/**
 * build-nav-menu.mjs — writes data/nav-menu.json, the content of the site bar's mega menu (js/rz-mega-menu.js).
 *
 * Owner, 2026-11-18: "elevate this with a mega menu … include some more columns … make the fourth column a visual
 * supporter for any highlighted menu item". standarization/SITE_CHROME_STANDARD.md §2b.
 *
 * Every item comes from a source that already exists, so a new calculator or a new article appears without a hand
 * edit to the menu:
 *   - calculators: data/calculators.json (title), grouped by GROUP_OF below; an unknown calculator lands in
 *     "Design & readiness" rather than being dropped;
 *   - articles: data/journal.json (the newest by date, its title and excerpt);
 *   - series: data/journal.json series (label + page);
 *   - hubs, labs and the BMS entry points: the curated list below, LINKS only (the cockpits keep their own bar).
 * The one-line description of a page is its own <meta name="description"> (first sentence, cut at a word), the
 * picture is its Open Graph card assets/og/<slug>.webp when that file exists, otherwise null (the menu draws a
 * neutral block, never a broken image).
 *
 * It refuses to write a menu with a link to a file that does not exist.
 *
 *   node tools/build-nav-menu.mjs           write data/nav-menu.json
 *   node tools/build-nav-menu.mjs --check   exit 1 when data/nav-menu.json is not what the sources produce
 */
import { readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'data/nav-menu.json');
const CHECK = process.argv.includes('--check');
const PER_GROUP = 6;
const LATEST = 5;

const GROUP_OF = { capex: 'cost', opex: 'cost', tco: 'cost', roi: 'cost', carbon: 'cost' };

const HUBS = [
  { href: 'datacenter-solutions.html', title: 'DC Solutions hub' },
  { href: 'tools.html', title: 'Tools & calculators' },
  { href: 'compare.html', title: 'Compare cases' },
  { href: 'cdu-hub.html', title: 'Liquid-cooling CDU toolkit' },
  { href: 'dc-conventional.html', title: 'DC Conventional cockpit', note: 'BMS' },
  { href: 'datahallAI.html', title: 'DC AI / HPC cockpit', note: 'BMS' }
];
const REFERENCE = [
  { href: 'dc-incidents.html', title: 'Incident library' },
  { href: 'glossary.html', title: 'Glossary' },
  { href: 'network-visualization-hub.html', title: 'Network protocol labs' },
  { href: 'standards-ltc-lab.html', title: 'LTC standards lab' },
  { href: 'manual/index.html', title: 'Technical manuals' }
];

const read = (p) => readFileSync(resolve(ROOT, p), 'utf8');
const unescape = (s) => s.replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#39;|&#x27;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&mdash;/g, '—').replace(/&ndash;/g, '–').replace(/&middot;/g, '·');

function fileOf(href) {
  const path = href.split('#')[0].split('?')[0];
  const f = resolve(ROOT, decodeURIComponent(path || 'index.html'));
  return existsSync(f) && statSync(f).isDirectory() ? resolve(f, 'index.html') : f;
}

/** first sentence of the page's meta description, cut at a word near 96 characters */
function oneLine(text) {
  let s = unescape(String(text || '')).replace(/\s+/g, ' ').trim();
  const stop = s.search(/[.:;!?](\s|$)/);
  if (stop > 24) s = s.slice(0, stop);
  if (s.length > 96) s = s.slice(0, s.lastIndexOf(' ', 93)).replace(/[,\s—–-]+$/, '') + '…';
  return s;
}
function describe(href) {
  const f = fileOf(href);
  const html = readFileSync(f, 'utf8');
  const m = html.match(/<meta\s+name="description"\s+content="([^"]*)"/i) || html.match(/<meta\s+content="([^"]*)"\s+name="description"/i);
  return m ? oneLine(m[1]) : '';
}
function image(href) {
  const slug = href.split('#')[0].split('?')[0].replace(/\/$/, '/index.html').replace(/\.html$/, '').replace(/\//g, '-');
  const p = `assets/og/${slug}.webp`;
  return existsSync(resolve(ROOT, p)) ? p : null;
}
const item = (href, title, extra) => Object.assign({ href, title, line: describe(href), image: image(href) }, extra || {});

const calcs = JSON.parse(read('data/calculators.json')).calculators;
const journal = JSON.parse(read('data/journal.json'));

const cost = [], design = [];
for (const c of calcs) (GROUP_OF[c.calc] === 'cost' ? cost : design).push(item(c.page, c.title));

const latest = journal.articles.slice()
  .sort((a, b) => String(b.date).localeCompare(String(a.date)) || Number(b.number) - Number(a.number))
  .slice(0, LATEST)
  .map((a) => ({ href: a.url, title: a.title, line: oneLine(a.excerpt), image: image(a.url) }));
const series = [item('articles.html', 'All articles')].concat(
  journal.series.map((s) => item(s.page, s.label)));

const menu = {
  _doc: 'GENERATED by tools/build-nav-menu.mjs from data/calculators.json, data/journal.json and the pages\' own meta descriptions — never hand-edit. Read by js/rz-mega-menu.js.',
  sections: [
    { id: 'home', label: 'Home', href: 'index.html' },
    {
      id: 'dc', label: 'DC Solutions', href: 'datacenter-solutions.html', featured: 'datacenter-solutions.html',
      groups: [
        { label: 'Cost & finance', items: cost.slice(0, PER_GROUP) },
        { label: 'Design & readiness', items: design.slice(0, PER_GROUP) },
        { label: 'Hubs & simulators', items: HUBS.map((h) => item(h.href, h.title, h.note ? { note: h.note } : null)) }
      ]
    },
    { id: 'results', label: 'Results', href: 'index.html#metrics', minor: true },
    { id: 'cases', label: 'Case Studies', href: 'index.html#case-studies', minor: true },
    {
      id: 'insights', label: 'Insights', href: 'articles.html', featured: latest.length ? latest[0].href : 'articles.html',
      groups: [
        { label: 'Latest articles', items: latest },
        { label: 'Series', items: series.slice(0, PER_GROUP) },
        { label: 'Reference & labs', items: REFERENCE.map((h) => item(h.href, h.title)) }
      ]
    },
    { id: 'faq', label: 'FAQ', href: 'index.html#faq', minor: true },
    { id: 'contact', label: 'Contact', href: 'index.html#contact' }
  ]
};
/* a calculator past the per-group cap is not dropped silently: it is named here, and tools.html lists every tool */
const overflow = cost.slice(PER_GROUP).concat(design.slice(PER_GROUP));
if (overflow.length) console.warn(`note: ${overflow.length} calculator(s) beyond ${PER_GROUP} per group are reached through tools.html: ${overflow.map((o) => o.href).join(', ')}`);

/* no dead link, no invented page */
const dead = [];
for (const s of menu.sections) {
  const all = [s].concat(...(s.groups || []).map((g) => g.items));
  for (const it of all) if (it.href && !existsSync(fileOf(it.href))) dead.push(it.href);
  if (s.featured && !(s.groups || []).some((g) => g.items.some((i) => i.href === s.featured))) dead.push(`featured ${s.featured} is not an item of ${s.id}`);
}
if (dead.length) { console.error('build-nav-menu: refusing — links to missing files: ' + dead.join(', ')); process.exit(1); }

const text = JSON.stringify(menu, null, 2) + '\n';
/* the nested loads carry the hash of what they load, so a changed menu, script or stylesheet reaches a returning
   visitor: data/nav-menu.json <- js/rz-mega-menu.js <- js/rz-chrome.js, and css/rz-nav-float.css <- css/rz-chrome.css.
   The pages' own tokens on rz-chrome.js / rz-chrome.css follow with tools/test-asset-cache-tokens.mjs --fix. */
const CHAIN = [
  { file: 'js/rz-mega-menu.js', target: 'data/nav-menu.json', re: /(data\/nav-menu\.json\?v=)[0-9a-f]{8}/ },
  { file: 'js/rz-chrome.js', target: 'js/rz-mega-menu.js', re: /(js\/rz-mega-menu\.js\?v=)[0-9a-f]{8}/ },
  { file: 'css/rz-chrome.css', target: 'css/rz-nav-float.css', re: /(rz-nav-float\.css\?v=)[0-9a-f]{8}/ },
];
const hash8 = (buf) => createHash('sha256').update(buf).digest('hex').slice(0, 8);
function stampChain(write) {
  const stale = [];
  for (const c of CHAIN) {
    const p = resolve(ROOT, c.file), src = readFileSync(p, 'utf8');
    const body = c.target === 'data/nav-menu.json' ? text : readFileSync(resolve(ROOT, c.target));
    if (!c.re.test(src)) { stale.push(`${c.file} has no ${c.target}?v= token`); continue; }
    const next = src.replace(c.re, `$1${hash8(body)}`);
    if (next !== src) { stale.push(`${c.file} -> ${c.target}`); if (write) writeFileSync(p, next); }
  }
  return stale;
}
if (CHECK) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== text) { console.error('data/nav-menu.json is STALE — run: node tools/build-nav-menu.mjs'); process.exit(1); }
  const drift = stampChain(false);
  if (drift.length) { console.error('nav float tokens are STALE (' + drift.join('; ') + ') — run: node tools/build-nav-menu.mjs'); process.exit(1); }
  console.log('data/nav-menu.json current; nav float tokens current');
} else {
  writeFileSync(OUT, text);
  const restamped = stampChain(true);
  if (restamped.length) console.log('restamped: ' + restamped.join('; '));
  const n = menu.sections.reduce((k, s) => k + (s.groups || []).reduce((m, g) => m + g.items.length, 0), 0);
  console.log(`wrote data/nav-menu.json: ${menu.sections.length} sections, ${n} menu items`);
}
