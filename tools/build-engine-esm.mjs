#!/usr/bin/env node
/**
 * build-engine-esm.mjs — PRD-P19 part A: rz-engine.js as an ES module.
 *
 * Wraps the browser IIFE byte-for-byte (no source rewrite) and writes
 * dist/rz-engine.mjs, whose default export is the same RZEngine object the
 * browser global holds. The IIFE attaches to its `root` argument
 * (`typeof window !== 'undefined' ? window : this`), so the wrapper declares a
 * module-scoped `window`: the real global when a DOM exists (browser ESM), a
 * small shim otherwise (Node). Nothing is written to globalThis in Node.
 *
 *   node tools/build-engine-esm.mjs            write dist/rz-engine.mjs
 *   node tools/build-engine-esm.mjs --check    exit 1 when the file differs from a fresh build
 *
 * The parity and freshness gate is tools/test-engine-esm.mjs.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCE = resolve(ROOT, 'rz-engine.js');
export const OUT = resolve(ROOT, 'dist/rz-engine.mjs');

/* Load the IIFE in a vm with the same shim the wrapper uses, to read the model surface. */
export function loadInVm(src) {
  const win = { console: console };
  win.window = win;
  win.localStorage = { getItem() { return null; }, setItem() {}, removeItem() {} };
  win.CustomEvent = function () {}; win.dispatchEvent = function () { return true; };
  win.addEventListener = function () {}; win.removeEventListener = function () {};
  vm.runInContext(src, vm.createContext(win), { filename: 'rz-engine.js' });
  if (!win.RZEngine) throw new Error('RZEngine did not attach to its root');
  return win.RZEngine;
}

function params(fn) {
  const m = /^[^(]*\(([^)]*)\)/.exec(Function.prototype.toString.call(fn));
  return (m ? m[1].split(',') : []).map((p) => p.replace(/\/\*.*?\*\//g, '').split('=')[0].trim()).filter((p) => /^[A-Za-z_$][\w$]*$/.test(p));
}

/* JSDoc typedef of every model namespace and its public functions (name + parameter names).
 * Return types are `any`: the engine carries no type information to derive them from. */
export function typedef(E) {
  const lines = ['/**', ' * @typedef {Object} RZModels Every RZEngine.models namespace and its public functions.'];
  for (const m of Object.keys(E.models).sort()) {
    const ns = E.models[m];
    if (!ns || typeof ns !== 'object') continue;
    const fns = Object.keys(ns).filter((f) => typeof ns[f] === 'function' && f.charAt(0) !== '_').sort();
    const sig = fns.map((f) => f + ': (' + params(ns[f]).map((p) => p + '?: any').join(', ') + ') => any');
    lines.push(' * @property {{' + sig.join(', ') + '}} ' + m);
  }
  lines.push(' */');
  return lines.join('\n');
}

export function build(src) {
  const sha = createHash('sha256').update(src).digest('hex').slice(0, 16);
  const head = [
    '// GENERATED by tools/build-engine-esm.mjs from rz-engine.js (sha256 ' + sha + ') - do not edit.',
    '// PRD-P19 part A. Usage: import RZEngine from \'./dist/rz-engine.mjs\';',
    '// The browser IIFE below is unchanged; `window` is module-scoped: the real global when a DOM exists,',
    '// otherwise a shim, so a Node import never touches globalThis.',
    'const window = (typeof globalThis.document !== \'undefined\') ? globalThis : (function () {',
    '  var s = { console: globalThis.console };',
    '  s.window = s;',
    '  s.localStorage = { getItem: function () { return null; }, setItem: function () {}, removeItem: function () {} };',
    '  s.CustomEvent = function () {};',
    '  s.dispatchEvent = function () { return true; };',
    '  s.addEventListener = function () {};',
    '  s.removeEventListener = function () {};',
    '  return s;',
    '})();',
    ''
  ].join('\n');
  const tail = [
    '',
    typedef(loadInVm(src)),
    '/** @type {{data: Object, format: Object, events: Object, models: RZModels}} The RZEngine object (standarization/SUPER_ENGINE.md). */',
    'const RZEngine = window.RZEngine;',
    'export default RZEngine;',
    '/** @type {Object} */',
    'export const data = RZEngine.data;',
    '/** @type {RZModels} */',
    'export const models = RZEngine.models;',
    '/** @type {Object} */',
    'export const format = RZEngine.format;',
    ''
  ].join('\n');
  return head + src + (src.endsWith('\n') ? '' : '\n') + tail;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const t0 = Date.now();
  const out = build(readFileSync(SOURCE, 'utf8'));
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(OUT, 'utf8'); } catch (e) { /* missing */ }
    if (cur !== out) { console.log('dist/rz-engine.mjs is STALE - run node tools/build-engine-esm.mjs'); process.exit(1); }
    console.log('dist/rz-engine.mjs fresh (' + out.length + ' bytes)');
  } else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, out);
    console.log('wrote dist/rz-engine.mjs (' + out.length + ' bytes, ' + (Date.now() - t0) + ' ms)');
  }
}
