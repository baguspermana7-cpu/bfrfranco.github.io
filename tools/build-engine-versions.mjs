#!/usr/bin/env node
/**
 * build-engine-versions.mjs — P16: the engine version a cockpit trusts is declared ONCE.
 *
 * Reads meta.version from js/conv-engine.js and js/dcai-engine.js and writes
 * js/rz-engine-versions.js:  window.RZ_ENGINE_VERSIONS = {conv:'x.y.z', dcai:'x.y.z'}
 *
 * The cockpits read their pin from that module instead of a typed literal, so an engine bump
 * is: edit the engine, run this generator, run `test-asset-cache-tokens.mjs --fix` for the
 * engine and this module. The module is generated, never typed (PRD-P16 §12).
 *
 *   node tools/build-engine-versions.mjs --apply   write the module
 *   node tools/build-engine-versions.mjs --check   exit 1 when the module is stale (freshness gate)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'js', 'rz-engine-versions.js');
const require = createRequire(import.meta.url);

function versionOf(file, key) {
  const mod = require(join(ROOT, 'js', file));
  const api = mod[key] || mod;
  const v = api && api.snapshot && api.snapshot.meta && api.snapshot.meta.version;
  if (!/^\d+\.\d+\.\d+$/.test(String(v || ''))) throw new Error(`${file}: snapshot.meta.version missing or not semver (${v})`);
  return v;
}

require(join(ROOT, 'js', 'dcai-model.js'));
const versions = { conv: versionOf('conv-engine.js', 'CONV_CALC'), dcai: versionOf('dcai-engine.js', 'DCAI_CALC') };

const body = `/* GENERATED by tools/build-engine-versions.mjs — do not edit by hand (PRD-P16).
   The engine version each cockpit trusts. Missing module = no pin = the cockpit fails CLOSED. */
(function (root) {
  'use strict';
  root.RZ_ENGINE_VERSIONS = Object.freeze({ conv: '${versions.conv}', dcai: '${versions.dcai}' });
})(typeof window !== 'undefined' ? window : globalThis);
`;

const mode = process.argv.includes('--apply') ? 'apply' : 'check';
const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
if (mode === 'apply') {
  if (current !== body) writeFileSync(OUT, body);
  console.log(`wrote js/rz-engine-versions.js — conv ${versions.conv}, dcai ${versions.dcai}${current === body ? ' (unchanged)' : ''}`);
} else if (current !== body) {
  console.log(`STALE js/rz-engine-versions.js — engines publish conv ${versions.conv}, dcai ${versions.dcai}; run --apply`);
  process.exit(1);
} else {
  console.log(`fresh — conv ${versions.conv}, dcai ${versions.dcai}`);
}
