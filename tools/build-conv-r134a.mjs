#!/usr/bin/env node
/* build-conv-r134a.mjs — writes the R-134a property rows js/conv-engine.js uses for the chiller refrigeration cycle
   (PRD-CONV-EQUIPMENT-INSIDE §5.2) from the NIST WebBook files in data/sources/nist-r134a/ (README there).
   Block between the markers R134A-PROPS:BEGIN / R134A-PROPS:END:
     R134A_SAT  = [[T °C, P kPa abs, hf, hg kJ/kg, sf, sg kJ/kg·K], ...]  saturation rows −12 … 72 °C, as published
     R134A_VAP  = { P kPa: [[T, h, s], ...] }  vapour rows of each isobar: the saturated-vapour row + every even °C ≤ 100
   node tools/build-conv-r134a.mjs [--check] */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'data/sources/nist-r134a');
const ENGINE = path.join(ROOT, 'js/conv-engine.js');
const BEGIN = '/* R134A-PROPS:BEGIN — generated by tools/build-conv-r134a.mjs from data/sources/nist-r134a (NIST WebBook SRD 69); do not edit */';
const END = '/* R134A-PROPS:END */';

function table(file) {
  const L = fs.readFileSync(path.join(SRC, file), 'utf8').trim().split('\n');
  const H = L[0].split('\t');
  return { H, rows: L.slice(1).map((l) => l.split('\t')) };
}
const col = (H, name) => { const i = H.indexOf(name); if (i < 0) throw new Error('column not found: ' + name); return i; };
const r = (v, d) => Number(Number(v).toFixed(d));

export function build() {
  const s = table('saturation.tsv');
  const iT = col(s.H, 'Temperature (C)'), iP = col(s.H, 'Pressure (kPa)');
  const ihf = col(s.H, 'Enthalpy (l, kJ/kg)'), ihg = col(s.H, 'Enthalpy (v, kJ/kg)');
  const isf = col(s.H, 'Entropy (l, J/g*K)'), isg = col(s.H, 'Entropy (v, J/g*K)');
  const sat = s.rows.map((c) => [r(c[iT], 3), r(c[iP], 2), r(c[ihf], 3), r(c[ihg], 3), r(c[isf], 5), r(c[isg], 5)])
    .filter((x) => x[0] >= -12 && x[0] <= 72).sort((a, b) => a[0] - b[0]);
  const vap = {};
  for (let P = 300; P <= 1700; P += 100) {
    const t = table('isobar-' + P + '.tsv');
    const jT = col(t.H, 'Temperature (C)'), jh = col(t.H, 'Enthalpy (kJ/kg)'), js = col(t.H, 'Entropy (J/g*K)'), jph = col(t.H, 'Phase');
    const rows = t.rows.filter((c) => c[jph] === 'vapor');
    const satRow = t.rows.find((c) => c[jph] === 'vapor');
    vap[P] = rows.filter((c, k) => k === 0 || (Number(c[jT]) % 2 === 0)).map((c) => [r(c[jT], 3), r(c[jh], 3), r(c[js], 5)]);
    if (!satRow) throw new Error('no vapour row at ' + P);
  }
  const lines = [BEGIN,
    '    var R134A_SAT = ' + JSON.stringify(sat) + ';',
    '    var R134A_VAP = ' + JSON.stringify(vap) + ';',
    '    ' + END];
  return '    ' + lines.join('\n');
}

const src = fs.readFileSync(ENGINE, 'utf8');
const a = src.indexOf(BEGIN), b = src.indexOf(END);
if (a < 0 || b < 0) { console.error('markers not found in js/conv-engine.js'); process.exit(1); }
const lineStart = src.lastIndexOf('\n', a) + 1;
const cur = src.slice(lineStart, b + END.length);
const next = build();
if (process.argv.includes('--check')) {
  if (cur !== next) { console.log('FAIL — js/conv-engine.js R134A-PROPS block is stale: run node tools/build-conv-r134a.mjs'); process.exit(1); }
  console.log('PASS — R134A-PROPS block equals a fresh build of data/sources/nist-r134a'); process.exit(0);
}
fs.writeFileSync(ENGINE, src.slice(0, lineStart) + next + src.slice(b + END.length));
console.log('wrote R134A-PROPS block (' + next.length + ' bytes)');
